def _numline(lo, hi):
    f = Fig(280, 90)
    f.seg((lo - 0.6, 0), (hi + 0.6, 0), w=1.0)
    f.path(lambda T, k: (lambda a: f'M{a[0] - 5:.2f},{a[1] - 3:.2f} L{a[0]:.2f},{a[1]:.2f} L{a[0] - 5:.2f},{a[1] + 3:.2f}')(T((hi + 0.6, 0))), w=1.0)
    f.path(lambda T, k: (lambda a: f'M{a[0] + 5:.2f},{a[1] - 3:.2f} L{a[0]:.2f},{a[1]:.2f} L{a[0] + 5:.2f},{a[1] + 3:.2f}')(T((lo - 0.6, 0))), w=1.0)
    for i in range(lo, hi + 1):
        f.seg((i, -0.12), (i, 0.12), w=0.8)
        f.text((i, -0.55), str(i).replace('-', '−'), size=9)
    f.dot((0, 0), 2.6).text((0, 0.6), 'P', size=10)
    return f.render()


