A, Bp, Cp, D = (0.0, 0.0), (5.0, 3.0), (5.0, -3.0), (10.0, 0.0)


def _curve(p, q, bend):
    def fn(T, k):
        a, b = T(p), T(q)
        mx, my = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
        dx, dy = b[0] - a[0], b[1] - a[1]
        l = math.hypot(dx, dy)
        cx, cy = mx - dy / l * bend, my + dx / l * bend
        return f'M{a[0]:.2f},{a[1]:.2f} Q{cx:.2f},{cy:.2f} {b[0]:.2f},{b[1]:.2f}'
    return fn


